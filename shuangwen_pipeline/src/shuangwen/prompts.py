def dumps(obj) -> str:
    return json.dumps(obj, ensure_ascii=False, indent=2)


def build_arc_plan_text(themes: list[str], arc_size: int) -> str:
    lines = []
    for i, theme in enumerate(themes):
        start = i * arc_size + 1
        lines.append(f"- 第{i + 1}卷（Ch{start}-{start + arc_size - 1}）：{theme}")
    return "\n".join(lines)


def build_writer_user_prompt(
    *,
    n: int,
    state_card_json: str,
    blacklist: list[str],
    tail_text: str,
    prev_beat: dict | None,
    beat: dict,
    next_beat: dict | None,
    sub_slices: dict[str, str],
    min_chars: int,
    max_chars: int,
) -> str:
    """组装第 N 章的动态 payload（全局状态卡 / 细纲窗口 / 尾部滑窗 / 切片素材 / 防越界锁）。"""
    slices_text = "（无）"
    if sub_slices:
        slices_text = "\n\n".join(f"〔{k}〕\n{v}" for k, v in sub_slices.items())
    prev_text = (
        f"第{prev_beat['chapter_num']}章《{prev_beat['title']}》：{prev_beat['payoff_and_hook']}"
        if prev_beat
        else "（无）"
    )
    next_text = (
        f"第{next_beat['chapter_num']}章《{next_beat['title']}》：{next_beat['core_conflict']}"
        if next_beat
        else "全书完"
    )
    return f"""\
【全局状态卡】：
{state_card_json}

【禁用老梗黑名单（本章严禁出现）】：{"、".join(blacklist) if blacklist else "（暂无）"}

【上一章细纲（已写完，只用于衔接）】：{prev_text}

【上一章结尾{len(tail_text)}字（请无缝衔接）】：
{tail_text}

【本章执行细纲（第{n}章：{beat['title']}）】：
- 核心冲突：{beat['core_conflict']}
- 搞笑打脸操作：{beat['comic_shuang_action']}
- 兑现与章末钩子：{beat['payoff_and_hook']}

【子模型素材参考（请彻底洗成你的大白话文风融入正文，不要原样照搬）】：
{slices_text}

🚨【防越界死命令】：你只能写到“{beat['payoff_and_hook']}”为止！
绝对禁止触碰：{beat['hard_stop_boundary']}
绝对禁止提前写出下一章剧情（下一章预告：{next_text}）！

字数要求：{min_chars}-{max_chars} 个汉字。直接输出第{n}章正文（不要标题、不要解释）。
"""
